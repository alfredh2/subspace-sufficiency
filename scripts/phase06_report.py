"""Applies the pre-registered Phase 0.6 decision rule (docs/plans/phase06_plan.md) to results/phase06/evaluation.json and writes
results/phase06/report_tables.md. No thresholds are chosen here; they are the ones fixed in the plan."""
import argparse
import json

import numpy as np

from causal_subspaces.utils.config import ROOT

ap = argparse.ArgumentParser()
ap.add_argument("--tag", default="search")
a = ap.parse_args()
R = ROOT / "results" / "phase06"
SUF = "" if a.tag == "search" else f"_{a.tag}"
E = json.load(open(R / f"evaluation{SUF}.json"))
A, M, PT = E["ablation"], E["meta"], E["patching"]
S = json.load(open(R / a.tag / "search_summary.json")) if (R / a.tag / "search_summary.json").exists() else None
TRAIN_F = (S or {}).get("train_formats", ["num_orig", "ab_orig"])
FM = ["num_orig", "ab_orig", "num_rev", "ab_rev", "yn"]
HELD_FMT = [f for f in FM if f not in TRAIN_F]
I = A["intact"]
auc = lambda r, f: float(np.mean(list(r[f"logic/{f}"]["auc_by_split"].values())))
gap = lambda s: s["margin_mean_gold_aff"] - s["margin_mean_gold_rej"]
cands = [n for n in A if n.startswith("cand_")]
others = [n for n in A if n != "intact" and not n.startswith("cand_")]

def drop(n, f):
    return auc(I, f) - auc(A[n], f)

def transfer(group, n, pos):
    return PT[group][f"{n}|{pos}"]["transfer"]

def criteria(n):
    k = M[n]["rank"]
    rnd = [m for m in A if m.startswith(f"rand_k{k}_")]
    c = {}
    d_orig = drop(n, "num_orig")
    others_ok = [f for f in FM[1:] if drop(n, f) >= 0.10]
    r_drop = max(drop(m, "num_orig") for m in rnd)
    c["1_logic_auc_drop"] = (d_orig >= 0.15 and len(others_ok) >= 2 and any(f in HELD_FMT for f in others_ok) and r_drop < 0.03,
                             f"Δ num_orig {d_orig:+.3f}; other formats ≥0.10: {others_ok}; matched-random max {r_drop:+.3f}")
    s = A[n]["logic/num_orig"]
    shift = s["margin_mean"] - I["logic/num_orig"]["margin_mean"]
    c["2_not_bias_shift"] = (abs(shift) <= 0.25 * gap(I["logic/num_orig"]) and abs(s["pred_aff"] - 0.5) <= 0.15,
                             f"Δ mean margin {shift:+.1f} (limit {0.25 * gap(I['logic/num_orig']):.1f}); P(valid) {s['pred_aff']:.2f}")
    dl, dp = (auc(I, 0) if False else I[f"control/{t}"]["auc"] - A[n][f"control/{t}"]["auc"] for t in ("language_localizer", "prontoqa"))
    vf = {t: A[n][f"control/{t}"]["margin_mean"] - I[f"control/{t}"]["margin_mean"] for t in ("mmlu_binary", "stroop", "word_recall_48")}
    c["3_selective"] = (dl < 0.05 and dp < 0.05 and all(abs(v) < 1 for v in vf.values()) and A[n]["lm_kl"] < 0.02,
                        f"Δ AUC localizer {dl:+.3f}, PrOntoQA {dp:+.3f}; verdict-free margin shifts {{{', '.join(f'{t}:{v:+.2f}' for t, v in vf.items())}}}; WikiText KL {A[n]['lm_kl']:.3f}")
    tm = transfer("match_num_orig", n, "all")
    rt = max(abs(transfer("match_num_orig", m, "all")) for m in rnd)
    off = {t: transfer(f"unmatched_{t}", n, "last") for t in ("language_localizer", "prontoqa", "mmlu_binary", "stroop")}
    c["4_patching"] = (tm >= 0.2 and rt < 0.02 and all(abs(v) < 0.1 for v in off.values()),
                       f"matched transfer {tm:+.3f} (random max {rt:.3f}); off-target " + ", ".join(f"{t}:{v:+.3f}" for t, v in off.items()))
    return c

md = [f"# Phase 0.6 tables, tag `{a.tag}`, search formats {TRAIN_F} (auto-generated by scripts/phase06_report.py)\n"]
if S:
    md += ["## Search runs (validation set; search formats num_orig/ab_orig)\n", "| run | rank | seed | val total | val gap ratio (ablated/intact) | val AUC logic (intact→abl) | val AUC localizer | val AUC PrOntoQA | val Δ pair-mean margin |", "|---|---|---|---|---|---|---|---|---|"]
    for r in S["runs"]:
        md.append(f"| k{r['rank']}_s{r['seed']} | {r['rank']} | {r['seed']} | {r['val_total']:.3f} | {r['val_gap_ratio']:.2f} | {r['val_auc_logic_intact']:.3f}→{r['val_auc_logic']:.3f} | "
                  f"{r['val_auc_language_localizer_intact']:.3f}→{r['val_auc_language_localizer']:.3f} | {r['val_auc_prontoqa_intact']:.3f}→{r['val_auc_prontoqa']:.3f} | {r['val_mean_margin_shift']:+.2f} |")
    md.append("")
md += ["## Held-out ablation metrics (mean AUC over Items/Families/Nonwords per format; Δ = intact − ablated)\n",
       "| intervention | rank | var. share | " + " | ".join(f"AUC {f}" for f in FM) + " | gap num_orig | Δ mean margin | P(valid) | loc AUC | PrOntoQA AUC | MMLU acc | WikiText KL |", "|---|---|---|" + "---|" * (len(FM) + 7)]
tot_var = None
for n in ["intact"] + cands + others:
    r = A[n]
    md.append(f"| {n} | {M[n]['rank'] if n in M else '-'} | {(M[n]['variance'] if n in M else 0):.0f} | " + " | ".join(f"{auc(r, f):.3f}" for f in FM) +
              f" | {gap(r['logic/num_orig']):.1f} | {r['logic/num_orig']['margin_mean'] - I['logic/num_orig']['margin_mean']:+.1f} | {r['logic/num_orig']['pred_aff']:.2f} | "
              f"{r['control/language_localizer']['auc']:.3f} | {r['control/prontoqa']['auc']:.3f} | {r['control/mmlu_binary']['acc']:.3f} | {r['lm_kl']:.3f} |")
md += ["\n## Pre-registered criteria\n", "| candidate | 1 logic AUC drop | 2 not a bias shift | 3 selective | 4 patching | numbers |", "|---|---|---|---|---|---|"]
verdicts = {}
for n in cands + [o for o in others if o in ("consensus_dc", "mvs_s0_rank2") and False]:
    c = criteria(n)
    verdicts[n] = c
    md.append(f"| {n} | " + " | ".join("PASS" if c[k][0] else "fail" for k in c) + " | " + "<br>".join(f"{k}: {v[1]}" for k, v in c.items()) + " |")
md.append("\nFor contrast (criteria numbers, not candidates):\n")
for n in ("consensus_dc", "mvs_s0_rank2"):
    r = A[n]
    md.append(f"- {n}: Δ AUC logic num_orig {drop(n, 'num_orig'):+.3f}, Δ mean margin {r['logic/num_orig']['margin_mean'] - I['logic/num_orig']['margin_mean']:+.1f}, P(valid) {r['logic/num_orig']['pred_aff']:.2f}, "
              f"localizer AUC {r['control/language_localizer']['auc']:.3f}, PrOntoQA AUC {r['control/prontoqa']['auc']:.3f}, matched transfer {transfer('match_num_orig', n, 'all'):+.3f}")
md += ["\n## Candidate reproducibility across search seeds (principal-angle cosines of same-rank solutions)\n"]
for k, v in E["candidate_overlap"].items():
    md.append(f"- {k}: {[round(x, 3) for x in v]}")
md += ["\n## Patching (transfer; matched pairs all-position, then unmatched last-position)\n", "| coords | matched num_orig all | matched num_rev all | matched num_orig last | localizer | PrOntoQA | MMLU | Stroop | logic (unmatched) |", "|---|---|---|---|---|---|---|---|---|"]
for n in cands + others:
    g = lambda grp, pos: f"{transfer(grp, n, pos):+.3f}"
    md.append(f"| {n} | {g('match_num_orig', 'all')} | {g('match_num_rev', 'all')} | {g('match_num_orig', 'last')} | " + " | ".join(g(f'unmatched_{t}', 'last') for t in ("language_localizer", "prontoqa", "mmlu_binary", "stroop", "logic")) + " |")
passing = [n for n, c in verdicts.items() if all(v[0] for v in c.values())]
md.append(f"\n**Candidates passing criteria 1–4:** {passing if passing else 'none'}")
(R / f"report_tables{SUF}.md").write_text("\n".join(md))
json.dump({n: {k: bool(v[0]) for k, v in c.items()} for n, c in verdicts.items()}, open(R / f"criteria_verdicts{SUF}.json", "w"), indent=1)
print("\n".join(md))
