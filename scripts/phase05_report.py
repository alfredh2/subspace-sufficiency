"""Builds results/phase05/report_tables.md from the saved Phase 0.5 outputs (no model needed)."""
import json

import numpy as np

from causal_subspaces.utils.config import ROOT

R = ROOT / "results" / "phase05"
E1 = json.load(open(R / "exp1_exp4_stats.json"))["stats"]
E2 = json.load(open(R / "exp2_directions.json"))
E3 = json.load(open(R / "exp3_patching.json"))
E3b = json.load(open(R / "exp3b_nonverdict_patching.json"))
A3, A3b = np.load(R / "exp3_patching_arrays.npz"), np.load(R / "exp3b_arrays.npz")
SEEDS = [0, 1, 2]
CONDS = ["intact"] + [f"{m}_s{s}" for m in ("retain", "ablate") for s in SEEDS]
md = []

md += ["# Phase 0.5 tables (auto-generated by scripts/phase05_report.py)\n",
       "## Exp 1 — label / output-format interventions (768 logic examples = Items+Families+Nonwords; first-character accuracy)\n",
       "`acc` = semantic accuracy (answer maps to the instruction's own label for the true verdict). `P(valid)` = fraction of responses giving the *valid* verdict "
       "(semantic), `P(lit1st)` = fraction producing the label listed first in the instruction (literal). `invalid` = response outside the two labels. "
       "`AUC` = threshold-free discrimination of the valid-vs-invalid logit margin; `thr-acc` = accuracy of the best single margin threshold.\n"]
for fmt in ("num_orig", "num_rev", "ab_orig", "ab_rev", "yn"):
    md += [f"### format `{fmt}`\n", "| condition | acc | invalid | P(valid) | P(lit1st) | AUC | thr-acc | mean margin (valid−invalid logit) | top generated tokens | confusion gold→pred (valid: v/i/other ; invalid: v/i/other) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for c in CONDS:
        s = E1[f"logic/{fmt}/{c}"]
        cf = s["confusion"]
        md.append(f"| {c} | {s['acc']:.3f} | {s['invalid_rate']:.3f} | {s['pred_aff']:.2f} | {s['pred_literal_first']:.2f} | {s['auc']:.3f} | {s['best_threshold_acc']:.3f} | {s['margin_mean']:+.1f} | "
                  f"{dict(list(s['token_counts'].items())[:3])} | {cf['aff']['aff']}/{cf['aff']['rej']}/{cf['aff']['other']} ; {cf['rej']['aff']}/{cf['rej']['rej']}/{cf['rej']['other']} |")
    md.append("")
md += ["Intact accuracy per split (num_orig): " + ", ".join(f"{k} {v:.3f}" for k, v in E1["logic/num_orig/intact"]["acc_by_split"].items()) + "\n"]

md += ["## Exp 4 — decision-bias decomposition (original 1/2 mapping; 'aff' = token 1)\n",
       "Margin = logit(1) − logit(2). Decomposition: mean raw logit of each answer token (relative to intact), class-conditional mean margins (gap = valid/true/English − invalid/false/nonsense), within-class SD, AUC.\n",
       "| task | condition | acc | P(1) | mean logit(1) | mean logit(2) | margin mean | gap (aff−rej) | within-class SD | d' | AUC | thr-acc |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for task in ("logic/num_orig", "control/language_localizer", "control/prontoqa", "control/mmlu_binary"):
    for c in CONDS:
        s = E1[f"{task}/{c}"]
        md.append(f"| {task} | {c} | {s['acc']:.3f} | {s['pred_aff']:.2f} | {s['mean_logit_aff']:.1f} | {s['mean_logit_rej']:.1f} | {s['margin_mean']:+.1f} | "
                  f"{s['margin_mean_gold_aff'] - s['margin_mean_gold_rej']:.1f} | {s['margin_within_std']:.1f} | {s['dprime']:.2f} | {s['auc']:.3f} | {s['best_threshold_acc']:.3f} |")
md.append("")
md += ["Ablation − intact change (mean over seeds 0,1,2), in logits:\n", "| task | Δ logit(1) | Δ logit(2) | Δ mean margin | Δ gap | Δ within-SD | AUC intact→ablated |", "|---|---|---|---|---|---|---|"]
for task in ("logic/num_orig", "control/language_localizer", "control/prontoqa", "control/mmlu_binary"):
    i = E1[f"{task}/intact"]
    ab = [E1[f"{task}/ablate_s{s}"] for s in SEEDS]
    f = lambda k: np.mean([a[k] for a in ab]) - i[k]
    gap = lambda x: x["margin_mean_gold_aff"] - x["margin_mean_gold_rej"]
    md.append(f"| {task} | {f('mean_logit_aff'):+.1f} | {f('mean_logit_rej'):+.1f} | {f('margin_mean'):+.1f} | {np.mean([gap(a) for a in ab]) - gap(i):+.1f} | {f('margin_within_std'):+.1f} | {i['auc']:.3f} → {np.mean([a['auc'] for a in ab]):.3f} |")
md.append("")

g = E2["geometry"]
md += ["## Exp 2 — directions\n", "Principal-angle cosines between rank-2 spans: " + "; ".join(f"seeds {k}: {[round(x, 3) for x in v['cosines']]}" for k, v in g["pairs"].items()),
       "\nShared-direction cosine across seeds: " + str({k: round(v, 3) for k, v in g["shared_vs_shared_cos"].items()}) +
       "; specific-direction cosine: " + str({k: round(v, 3) for k, v in g["specific_vs_specific_cos"].items()}) +
       "; consensus↔shared: " + str({k: round(v, 3) for k, v in g["consensus_cos_to_shared"].items()}) + "\n",
       "| intervention | Items | Families | Nonwords | P(1) | AUC | gap | mean margin | localizer acc (P(1)) | PrOntoQA | MMLU-bin | Stroop | word-recall-48 | mult | WikiText KL |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for k, v in E2["interventions"].items():
    st, c = v["logic_stats"], v["controls"]
    md.append(f"| {k} | {v['logic']['items']:.3f} | {v['logic']['families']:.3f} | {v['logic']['nonwords']:.3f} | {st['pred_aff']:.2f} | {st['auc']:.3f} | {st['margin_mean_gold_aff'] - st['margin_mean_gold_rej']:.1f} | {st['margin_mean']:+.1f} | "
              f"{c['language_localizer']['acc']:.3f} ({c['language_localizer']['stats']['pred_aff']:.2f}) | {c['prontoqa']['acc']:.3f} | {c['mmlu_binary']['acc']:.3f} | {c['stroop']['acc']:.3f} | {c['word_recall_48']['acc']:.2f} | {c['multiplication_1digit']['acc']:.2f} | {c['lm_kl']:.3f} |")
md.append("\nNote: rank-1 *retention* rows with accuracy ≈ 0 and P(1) ≈ 0 mean the model no longer emits '1'/'2' at all (output off-format), not that it answers wrongly; AUC refers to the logit margin of tokens 1 vs 2.\n")

def directional(arr, group, name, pos):
    ta, sa = arr[f"{group}|tgt_aff"], arr[f"{group}|src_aff"]
    mp, mt, ms = arr[f"{group}|m|{name}|{pos}"], arr[f"{group}|m_t"], arr[f"{group}|m_s"]
    out = {}
    for lab, sel in (("→valid/affirm (source aff, target rej)", sa & ~ta), ("→invalid/reject (source rej, target aff)", ~sa & ta)):
        sgn = 1.0 if "→valid" in lab else -1.0
        sh = sgn * (mp[sel] - mt[sel]); gp = sgn * (ms[sel] - mt[sel])
        out[lab] = (sh.mean(), gp.mean(), sh.mean() / gp.mean())
    return out

md += ["## Exp 3 — counterfactual patching of MVS coordinates\n",
       f"{E3['n_pairs']} matched pairs (same rule/antecedent/consequent sentences and marker; fact↔conclusion roles swapped: MP↔AC, MT↔DA, ± negated consequent), "
       f"mean {E3['mean_diff_tokens']:.1f} differing token positions of equal-length prompts; test contents only. Each pair is used in both directions (896 trials). "
       "`transfer` = mean shift of the semantic margin toward the source ÷ mean source−target gap (1 = full transplant, 0 = nothing); `flip` = fraction of clean trials (target and source both answered correctly) whose verdict becomes the source's.\n"]
for gname in ("match_num_orig", "match_num_rev", "match_ab_orig"):
    md += [f"### {gname} ({E3['groups'][gname]['n_trials']} trials)\n", "| patched coordinates | pos | shift (logits) | gap | transfer | flip |", "|---|---|---|---|---|---|"]
    res = E3["groups"][gname]["results"]
    names = sorted({k.split("|")[0] for k in res})
    show = [n for n in names if not n.startswith("rand_")]
    for n in show:
        for pos in ("all", "last"):
            r = res[f"{n}|{pos}"]
            md.append(f"| {n} | {pos} | {r['shift_mean']:+.2f} ± {r['shift_sem']:.2f} | {r['gap_mean']:.1f} | {r['transfer']:+.3f} | {r['flip_to_source']:.3f} |")
    for kind in ("rand_gauss", "rand_topvar"):
        rn = [n for n in names if n.startswith(kind)]
        for pos in ("all", "last"):
            tr = [res[f"{n}|{pos}"]["transfer"] for n in rn]
            md.append(f"| {kind} (n={len(rn)}) | {pos} | max \\|transfer\\| {max(map(abs, tr)):.4f} | | mean {np.mean(tr):+.4f} | max flip {max(res[f'{n}|{pos}']['flip_to_source'] for n in rn):.3f} |")
    md.append("")
md += ["### Direction of patching (asymmetry), num_orig, MVS rank-2 and shared/specific directions\n", "| coordinates | pos | → valid: shift / gap / transfer | → invalid: shift / gap / transfer |", "|---|---|---|---|"]
for n in ["mvs_s0", "mvs_s1", "mvs_s2", "consensus", "s0_specific"]:
    for pos in ("all", "last"):
        d = directional(A3, "match_num_orig", n, pos)
        (a1, a2) = d.values()
        md.append(f"| {n} | {pos} | {a1[0]:+.1f} / {a1[1]:.1f} / {a1[2]:+.2f} | {a2[0]:+.1f} / {a2[1]:.1f} / {a2[2]:+.2f} |")
md += ["\n### Lexical control (same label, different words): patching must not change the verdict\n", "| group | coords | pos | mean abs margin change | verdict change rate |", "|---|---|---|---|---|"]
for gname in ("lexctrl_num_orig", "lexctrl_num_rev"):
    for n in ("mvs_s0", "mvs_s1", "mvs_s2", "complement_s0"):
        for pos in ("all", "last"):
            r = E3["groups"][gname]["results"][f"{n}|{pos}"]
            md.append(f"| {gname} | {n} | {pos} | {r['abs_shift_mean']:.2f} | {r['verdict_change_rate']:.3f} |")
md += ["\n### Same protocol (unmatched pairs, last-position patch) across tasks\n", "| task | coords | transfer | flip | → affirm direction transfer | → reject direction transfer |", "|---|---|---|---|---|---|"]
for src_, A in ((E3, A3), (E3b, A3b)):
    for gname, gd in src_["groups"].items():
        if not gname.startswith("unmatched"):
            continue
        for n in ("mvs_s0", "mvs_s1", "mvs_s2", "complement_s0"):
            r = gd["results"][f"{n}|last"]
            d = directional(A, gname, n, "last")
            (a1, a2) = d.values()
            md.append(f"| {gname[10:]} | {n} | {r['transfer']:+.3f} | {r['flip_to_source']:.3f} | {a1[2]:+.2f} | {a2[2]:+.2f} |")
        rr = [v["transfer"] for k, v in gd["results"].items() if k.startswith("rand_") and k.endswith("|last")]
        md.append(f"| {gname[10:]} | random (n={len(rr)}) | max \\|{max(map(abs, rr)):.4f}\\| | | | |")
(R / "report_tables.md").write_text("\n".join(md))
print("\n".join(md[-60:]))
