# -------------------------------------------------- Stage 4
M = lambda n: ST[f"{n}||margin"]
def gap(n, g, rows=None):
    m_, a_ = M(n)[GR == g], AC[GR == g]
    if rows is not None: m_, a_ = m_[rows], a_[rows]
    return m_[a_].mean() - m_[~a_].mean()
def Eg(n, g, rows=None):
    d0, dd = gap("intact", g, rows), gap("dc_ablation", g, rows)
    return (d0 - gap(n, g, rows)) / (d0 - dd)
def shift(n, g): return float(M(n)[GR == g].mean() - M("intact")[GR == g].mean())
def fam(prefix, k, dn="consensus"): return [n for n in names if n.startswith(f"{prefix}|{dn}|k={k}|")]
TASKS = ["logic_num_orig", "logic_num_rev", "localizer", "prontoqa"]
rng = np.random.default_rng(0)
def boot_diff(native, controls, g, nb=300):
    n_g = int((GR == g).sum()); out = []
    for _ in range(nb):
        rows = rng.integers(0, n_g, n_g)
        out.append(Eg(native, g, rows) - np.mean([Eg(c, g, rows) for c in controls]))
    return float(np.quantile(out, .025)), float(np.quantile(out, .975))

md += ["\n## Stage 4 — causal ablation (mean replacement at all positions; eval subsets held-out)\n",
       "E_gap^T = fraction of the answer-margin class-gap loss caused by full d_c ablation that the intervention reproduces (1 = same as d_c ablation). Intact class gaps (logits): " + ", ".join(f"{g}: {gap('intact', g):.1f}" for g in np.unique(GR)) + "; d_c-ablation gaps: " + ", ".join(f"{g}: {gap('dc_ablation', g):.1f}" for g in TASKS) + ".\n",
       "| intervention | k | E_gap logic num_orig | E_gap logic num_rev | E_gap localizer | E_gap PrOntoQA | E_shift logic num_orig | verdict-coordinate class-gap at hook (intact 19.3) | direct class-gap change | mean ‖Δh_hook‖ | WikiText KL | verdict-free shifts (MMLU / Stroop / word recall) |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
def cgap_c(n, g="logic_num_orig"):
    c_, a_ = ST[f"{n}||c"][GR == g], AC[GR == g]; return float(c_[a_].mean() - c_[~a_].mean())
def dgap(n, g="logic_num_orig"):
    d_, a_ = ST[f"{n}||direct"][GR == g], AC[GR == g]
    return float(d_[a_].mean() - d_[~a_].mean()) if not np.all(np.isnan(d_)) else float("nan")
def Pn(n): return float(ST[f"{n}||dh"][GR == "logic_num_orig"].mean())
def row(n, label, k_=""):
    ml(f"| {label} | {k_} | " + " | ".join(f"{Eg(n, g):.3f}" for g in TASKS) + f" | {shift(n, 'logic_num_orig') / shift('dc_ablation', 'logic_num_orig'):.3f} | {cgap_c(n):.1f} | {dgap(n):+.1f} | {Pn(n):.1f} | {float(ST[f'{n}||kl']):.3f} | "
       f"{shift(n, 'mmlu_binary'):+.2f} / {shift(n, 'stroop'):+.2f} / {shift(n, 'word_recall_48'):+.2f} |")
K = [4, 16, 64, 256, 512, 2458]
for k in K:
    row(f"native|consensus|k={k}|mean|all", "native top-k (consensus, |Δ| ranking)", k)
for k in K:
    row(f"actonly|consensus|k={k}|mean|all", "activation-only top-k (E[a²])", k)
for n_, lab in (("native|consensus|k=512|mean|last", "native, last position only"), ("native|consensus|k=64|zero|all", "native, zero replacement"), ("native|consensus|k=512|zero|all", "native, zero replacement")):
    if n_ in names: row(n_, lab, n_.split("k=")[1].split("|")[0])
md.append("")

fams = ["random", "actmatched", "alignmatched", "rotated_top", "rotated_random"]
md += ["\n### Controls (E_gap, mean [min, max] over draws; empirical p that a control draw ≥ native; bootstrap 95 % CI of E_native − mean(E_control) over eval examples)\n", "| k | control | n | " + " | ".join(f"{g}" for g in TASKS) + " | mean ‖Δh‖ | WikiText KL (max) | verdict-free max |shift| |", "|---|---|---|" + "---|" * (len(TASKS) + 3)]
C2 = {}
for k in K:
    nat = f"native|consensus|k={k}|mean|all"
    for f in fams:
        cs = fam(f, k)
        if not cs: continue
        cells = []
        for g in TASKS:
            e = [Eg(c, g) for c in cs]
            p = C.empirical_p(Eg(nat, g), e)
            if len(cs) >= 20 and f in ("random", "actmatched", "alignmatched"):
                lo, hi = boot_diff(nat, cs, g, 200); C2[(k, f, g)] = (p, lo, hi)
                cells.append(f"{np.mean(e):.3f} [{np.min(e):.3f}, {np.max(e):.3f}]; p={p:.3f}; CI[{lo:+.2f},{hi:+.2f}]")
            else:
                cells.append(f"{np.mean(e):.3f} [{np.min(e):.3f}, {np.max(e):.3f}]" + (f"; p={p:.2f}" if len(cs) >= 10 else ""))
        vf = max(max(abs(shift(c, x)) for x in ("mmlu_binary", "stroop", "word_recall_48")) for c in cs)
        md.append(f"| {k} | {f} | {len(cs)} | " + " | ".join(cells) + f" | {np.mean([Pn(c) for c in cs]):.1f} | {max(float(ST[c + '||kl']) for c in cs):.3f} | {vf:.2f} |")

# matched perturbation strength
md += ["\n### Matched perturbation strength (logic num_orig): control-family E_gap interpolated at the native set's mean ‖Δh_hook‖\n", "| native k | native ‖Δh‖ | native E_gap | " + " | ".join(fams) + " |", "|---|---|---|" + "---|" * len(fams)]
match = {}
for k in (64, 512):
    nat = f"native|consensus|k={k}|mean|all"; pn = Pn(nat); cells = []
    for f in fams:
        pts = sorted((np.mean([Pn(c) for c in fam(f, kk)]), np.mean([Eg(c, "logic_num_orig") for c in fam(f, kk)])) for kk in K if fam(f, kk))
        xs, ys = zip(*pts); inside = xs[0] <= pn <= xs[-1]
        val = float(np.interp(np.log(pn), np.log(xs), ys)); match[(k, f)] = (val, inside)
        cells.append(f"{val:.3f}" + ("" if inside else " (extrapolated→clamped)"))
    md.append(f"| {k} | {pn:.1f} | {Eg(nat, 'logic_num_orig'):.3f} | " + " | ".join(cells) + " |")

# cross-task causal + replication
md += ["\n### Cross-task and direction replication (k = 512)\n", "| set | E_gap logic num_orig | logic num_rev | localizer | PrOntoQA |", "|---|---|---|---|---|"]
for n_, lab in (("native|consensus|k=512|mean|all", "ranked by logic (primary)"), ("native_rankedby_localizer|consensus|k=512|mean|all", "ranked by localizer"), ("native_rankedby_prontoqa|consensus|k=512|mean|all", "ranked by PrOntoQA")):
    if n_ in names: ml(f"| {lab} | " + " | ".join(f"{Eg(n_, g):.3f}" for g in TASKS) + " |")
repl = {}
for dn in ("shared_s0", "shared_s1", "shared_s2"):
    n_ = f"native|{dn}|k=512|mean|all"
    if n_ in names:
        cs = fam("random", 512, dn) + fam("actmatched", 512, dn)
        repl[dn] = (Eg(n_, "logic_num_orig"), max(Eg(c, "logic_num_orig") for c in cs) if cs else float("nan"))
        ml(f"| {dn} (own gains/top-k) | " + " | ".join(f"{Eg(n_, g):.3f}" for g in TASKS) + f" | controls max (logic num_orig) {repl[dn][1]:.3f} |")
if G3:
    md += ["\nG3 for the other directions (k=512 signed reconstruction on held-out): " + "; ".join(f"{dn}: frac {r['k512']['frac']:.3f}, R² {r['k512']['r2']:.3f}, random max {r['random_frac_max']:.3f}" for dn, r in G3.items())]

# -------------------------------------------------- criteria
nat512 = "native|consensus|k=512|mean|all"
gc = {}
gc["G1"] = g12["cons/logic"][0]; gc["G2"] = g12["cons/logic"][1]; gc["G3"] = G3ok["cons"]
rep_dirs = sum(1 for a in ("cons/logic", "s0/logic", "s1/logic", "s2/logic") if g12[a][0] and g12[a][1]) 
rep_g3 = sum(1 for dn in ("consensus", "shared_s0", "shared_s1", "shared_s2") if (G3.get(dn) and (G3ok.get(dn) if dn != "consensus" else G3ok["cons"])))
dist_geo = bool(S23["analyses"]["cons/logic"]["native"]["pooled"]["top1%"][0] < 1.5 * np.mean(S23["analyses"]["cons/logic"]["nulls"]["true_haar"]["pooled"]["top1%"]) and g3["frac"] < 0.20)
sparse_geo = all(gc.values()) and rep_dirs >= 3 and (rep_g3 >= 3 if G3 else False)
cc = {}
cc["C1"] = Eg(nat512, "logic_num_orig") >= 0.30 and Eg(nat512, "logic_num_rev") >= 0.30
c2 = True; c2d = {}
for f in ("random", "actmatched", "alignmatched"):
    for g in ("logic_num_orig", "logic_num_rev"):
        if (512, f, g) in C2:
            p, lo, hi = C2[(512, f, g)]; ok = p <= 1 / 21 + 1e-9 and lo > 0; c2d[f"{f}/{g}"] = (round(p, 3), round(lo, 3), round(hi, 3), ok); c2 = c2 and ok
        else:
            c2 = False
cc["C2"] = bool(c2)
rt = np.mean([Eg(c, "logic_num_orig") for c in fam("rotated_top", 512)]) if fam("rotated_top", 512) else float("nan")
cc["C3"] = bool(rt < 0.10 and all(Eg(nat512, "logic_num_orig") - match[(512, f)][0] >= 0.15 for f in ("rotated_top", "rotated_random", "random")))
vf_nat = max(abs(shift(nat512, x)) for x in ("mmlu_binary", "stroop", "word_recall_48"))
cc["C4"] = bool(float(ST[f"{nat512}||kl"]) < 0.02 and vf_nat < 1.0)
cc["C5"] = bool(np.sign(dgap(nat512)) == np.sign(cgap_c(nat512) - cgap_c("intact")) and np.sign(dgap(nat512)) != 0)
e5 = Eg("native|consensus|k=2458|mean|all", "logic_num_orig")
ctrl_k5 = [Eg(c, "logic_num_orig") for f in ("random", "actmatched", "rotated_top") for c in fam(f, 2458)]
dist_caus = bool(e5 < 0.10 or (ctrl_k5 and Eg(nat512, "logic_num_orig") <= max(Eg(c, "logic_num_orig") for f in ("random", "actmatched", "alignmatched") for c in fam(f, 512))))
sparse_caus = all(cc.values())
md += ["\n## Frozen criteria, applied mechanically\n",
       f"Geometric (consensus): G1 {gc['G1']}, G2 {gc['G2']}, G3 {gc['G3']}; directions with G1&G2: {rep_dirs}/4; directions with G3: {rep_g3}/4 (G3 computed for {len(G3)} directions) → **{'G-sparse' if sparse_geo else ('G-distributed' if dist_geo else 'G-mixed')}**",
       f"Causal (consensus, k=512): C1 {cc['C1']} (E_gap {Eg(nat512, 'logic_num_orig'):.3f} / {Eg(nat512, 'logic_num_rev'):.3f}); C2 {cc['C2']} {c2d}; C3 {cc['C3']} (rotated-top E_gap {rt:.3f}; matched-strength interpolations {({f: round(match[(512, f)][0], 3) for f in fams})}); C4 {cc['C4']} (KL {float(ST[f'{nat512}||kl']):.3f}, max verdict-free shift {vf_nat:.2f} logits); C5 {cc['C5']} (direct class-gap change {dgap(nat512):+.1f}, actual {cgap_c(nat512) - cgap_c('intact'):+.1f}) → **{'C-sparse' if sparse_caus else ('C-distributed' if dist_caus else 'C-mixed')}**",
       f"Replication of causal effect for shared directions (logic num_orig E_gap vs control max): {({k_: (round(v_[0], 3), round(v_[1], 3)) for k_, v_ in repl.items()})}"]
overall = "SPARSE native implementation supported" if (sparse_geo and sparse_caus) else ("DISTRIBUTED implementation supported" if (dist_geo and dist_caus) else "MIXED / INCONCLUSIVE")
md.append(f"\n**Overall (mechanical): {overall}.**")
(R / "report_tables.md").write_text("\n".join(md))
json.dump(dict(geometric=gc, geometric_directions_g1g2=rep_dirs, geometric_directions_g3=rep_g3, causal=cc, C2_detail={str(k_): v_ for k_, v_ in c2d.items()}, overall=overall), open(R / "criteria_verdicts.json", "w"), indent=1, default=bool)
print("\n".join(md[-40:]))
