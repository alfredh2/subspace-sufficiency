        c["A2_detail"] = dict(min_gap_to_max_random=float(min(gap)), max_random_mean=float(max(rmean)), max_nonsummary=float(max(ns)))
        c["A2_random"] = bool(min(gap) >= 0.30 and max(rmean) <= 0.10); c["A2_nonsummary"] = bool(max(ns) <= 0.30); c["A2"] = bool(c["A2_random"] and c["A2_nonsummary"])
        # sensitivity: trials with no flagged random draw
