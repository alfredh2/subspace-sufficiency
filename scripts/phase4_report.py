f2 = lambda x: "—" if x is None else (f"{x:.2f}" if isinstance(x, (float, np.floating)) else str(x))
ci2 = lambda c: f"[{c[0]:.2f}, {c[1]:.2f}]"


def tcurve_rep(boot, tr, bt, bs, jobs, name, key):
    g = PL.getters()[key]; num, den = S.transfer_terms(tr["sigma"], g(jobs[name]), g(bt), g(bs)); return boot.ratio(num, den)


def load(fmt, stage="stage2"):
    tr, bt, bs, jobs = PL.load_raw(OUT / f"{stage}_{fmt}.npz"); boot = PL.S.Boot(tr["pair"], tr["content"], nboot=2000, seed=7); return tr, bt, bs, jobs, boot


def loco_onset(tr, bt, bs, jobs, cond, key, thr_frac=0.5):
    """Leave-one-content-out point-estimate sustained onset (no CIs): smallest i s.t. point T >= thr_frac*plateau for all i'>=i."""
    g = PL.getters()[key]; out = []
    for c in np.unique(tr["content"]):
        keep = tr["content"] != c; T = []
        for i in range(23):
            num, den = S.transfer_terms(tr["sigma"][keep], g(jobs[f"patch|{cond}|{i}"])[keep], g(bt)[keep], g(bs)[keep]); T.append(num.sum() / den.sum())
        T = np.array(T); plat = float(np.median(T[19:23])); thr = thr_frac * plat
        out.append(next((i for i in range(23) if (T[i:] >= thr).all()), None))
    return out


