def ratio(a, b):
    """a/b of two ratio objects (same resamples)."""
    return dict(point=a["point"] / b["point"], rep_pair=a["rep_pair"] / b["rep_pair"], rep_content=a["rep_content"] / b["rep_content"], loco=a["loco"] / b["loco"])


def diff(a, b):
    return dict(point=a["point"] - b["point"], rep_pair=a["rep_pair"] - b["rep_pair"], rep_content=a["rep_content"] - b["rep_content"], loco=a["loco"] - b["loco"])


def bounds(r):
    return dict(point=r["point"], pair=(np.percentile(r["rep_pair"], 2.5), np.percentile(r["rep_pair"], 97.5)), content=(np.percentile(r["rep_content"], 2.5), np.percentile(r["rep_content"], 97.5)),
                loco=(float(np.min(r["loco"])), float(np.max(r["loco"]))))


def fmt_stat(r):
    b = bounds(r); return f"{b['point']:.2f} {ci(*b['pair'])} / {ci(*b['content'])} (LOCO {b['loco'][0]:.2f}…{b['loco'][1]:.2f})"


def cond_ok(r, kind, lo=None, hi=None, point=None):
    """Evaluate a preregistered inequality on a ratio object: point and the stated bound for BOTH interval types, and the point inequality in every LOCO recomputation (set A)."""
    b = bounds(r); ok = True
    if point is not None: ok &= (b["point"] >= point[0] if point[1] == ">=" else b["point"] <= point[0])
    if kind == "lower_ge": ok &= b["pair"][0] >= lo and b["content"][0] >= lo
    if kind == "upper_le": ok &= b["pair"][1] <= hi and b["content"][1] <= hi
    if kind == "upper_lt": ok &= b["pair"][1] < hi and b["content"][1] < hi
    if kind == "lower_gt": ok &= b["pair"][0] > lo and b["content"][0] > lo
    if point is not None:
        loco = np.asarray(r["loco"]); ok &= bool((loco >= point[0]).all() if point[1] == ">=" else (loco <= point[0]).all())
    return bool(ok)


